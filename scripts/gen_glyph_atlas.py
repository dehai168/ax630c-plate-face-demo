#!/usr/bin/env python3
"""预渲染叠加用字形（ASCII + 车牌省份简称 + 少量中文），生成 src/glyph_atlas.h。
板端不依赖 FreeType/字体文件，程序里按 UTF-8 码点查表贴字形 alpha。
字体: Noto Sans CJK SC (SIL Open Font License 1.1)。
用法: python gen_glyph_atlas.py --font /usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc --out ../src/glyph_atlas.h
"""
import argparse
from PIL import Image, ImageDraw, ImageFont
ap = argparse.ArgumentParser()
ap.add_argument('--font', default='/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc')
ap.add_argument('--size', type=int, default=24)
ap.add_argument('--out', required=True)
a = ap.parse_args()
chars = [chr(c) for c in range(32, 127)]
chars += list("京津沪渝冀豫云辽黑湘皖鲁新苏浙赣鄂桂甘晋蒙陕吉闽贵粤青藏川宁琼使领学警挂港澳民航")
chars += list("蓝黄绿白色牌未知人脸车单双层耗时帧号")
seen = set(); chars = [c for c in chars if not (c in seen or seen.add(c))]
font = ImageFont.truetype(a.font, a.size, index=2 if a.font.endswith('.ttc') else 0)  # ttc index 2 = SC
asc, desc = font.getmetrics()
H = asc + desc
glyphs = []; x = 0; imgs = []
for ch in chars:
    w = int(round(font.getlength(ch)))
    w = max(w, 1)
    im = Image.new('L', (w, H), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=font, fill=255)
    imgs.append(im); glyphs.append((ord(ch), x, w)); x += w
atlas = Image.new('L', (x, H), 0)
for (cp, gx, w), im in zip(glyphs, imgs):
    atlas.paste(im, (gx, 0))
data = atlas.tobytes()
with open(a.out, 'w', encoding='utf-8') as f:
    f.write('// Auto-generated by scripts/gen_glyph_atlas.py, font: Noto Sans CJK SC (SIL OFL 1.1)\n#pragma once\n#include <cstdint>\n')
    f.write(f'static const int kGlyphAtlasW = {x};\nstatic const int kGlyphAtlasH = {H};\nstatic const int kGlyphCount = {len(glyphs)};\n')
    f.write('struct GlyphEntry { uint32_t cp; int x; int w; };\nstatic const GlyphEntry kGlyphs[] = {\n')
    for cp, gx, w in glyphs: f.write(f'  {{{cp}u, {gx}, {w}}},\n')
    f.write('};\nstatic const uint8_t kGlyphAtlas[] = {\n')
    for i in range(0, len(data), 32):
        f.write('  ' + ','.join(str(b) for b in data[i:i+32]) + ',\n')
    f.write('};\n')
print('glyphs', len(glyphs), 'atlas', x, 'x', H)
